#!/usr/bin/env python3
"""Generate the "Pioneer" theme for the Redmi Note 2 (LineageOS 14.1, Android 7.1)
as static resource overlays (RROs) for /vendor/overlay.

Android 7 has no adaptive icons, so every icon is pre-cut to a squircle PNG in
each launcher density (mdpi..xxxhdpi); the default wallpaper is overlaid in the
two configs framework-res uses on this phone (xxhdpi, nodpi).

usage: tools/theme/gen_overlays.py      (writes theme/overlays/)
then on the build box: tools/theme/build_overlays.sh (aapt2 + apksigner)
"""
import math, os, shutil
from PIL import Image, ImageDraw

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
ART = os.path.join(ROOT, "assets", "theme")
OUT = os.path.join(ROOT, "theme", "overlays")
DENS = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}

# art cell -> (overlay name, target package, [(res type, res name)])  names from `aapt2 dump badging`
APPS = [
    ("r2c1", "Dialer",      "com.android.dialer",       [("mipmap", "ic_launcher_phone")]),
    ("r2c2", "Messaging",   "com.android.messaging",    [("mipmap", "ic_launcher")]),
    ("r2c3", "Contacts",    "com.android.contacts",     [("mipmap", "ic_contacts_launcher")]),
    ("r2c4", "Calendar",    "com.android.calendar",     [("mipmap", "ic_launcher_calendar")]),
    ("r2c5", "DeskClock",   "com.android.deskclock",    [("mipmap", "ic_launcher_alarmclock")]),
    ("r1c3", "Snap",        "org.cyanogenmod.snap",     [("mipmap", "ic_launcher_camera")]),
    ("r1c4", "Gallery",     "com.android.gallery3d",    [("mipmap", "ic_launcher_gallery")]),
    ("r1c5", "Settings",    "com.android.settings",     [("mipmap", "ic_launcher_settings")]),
    ("r3c1", "DocumentsUI", "com.android.documentsui",  [("mipmap", "ic_launcher_filemanager")]),
    ("r3c2", "Jelly",       "org.lineageos.jelly",      [("mipmap", "ic_launcher")]),
    ("r3c4", "Eleven",      "com.cyanogenmod.eleven",   [("mipmap", "ic_launcher_eleven")]),
    ("r3c5", "Recorder",    "org.lineageos.recorder",   [("mipmap", "ic_launcher")]),
    ("r4c5", "Calculator",  "com.android.calculator2",  [("mipmap", "ic_launcher_calculator")]),
    ("r3c3", "Email",       "com.android.email",        [("mipmap", "ic_launcher_mail")]),
    ("r1c2", "Terminal",    "com.android.terminal",     [("drawable", "ic_launcher")]),
    ("r5c5", "Termux",      "com.termux",               [("mipmap", "ic_launcher"), ("mipmap", "ic_launcher_round")]),
]

MANIFEST = """<?xml version="1.0" encoding="utf-8"?>
<!-- generated by tools/theme/gen_overlays.py -->
<manifest xmlns:android="http://schemas.android.com/apk/res/android"
    package="org.redmi.theme.pioneer.{suffix}">
    <overlay android:targetPackage="{target}" android:priority="100" />
    <application android:hasCode="false" />
</manifest>
"""

def squircle(size, n=4.2):
    big = size * 4; r = big / 2; pts = []
    for i in range(1440):
        t = 2 * math.pi * i / 1440; c, s = math.cos(t), math.sin(t)
        pts.append((r + r * math.copysign(abs(c) ** (2 / n), c), r + r * math.copysign(abs(s) ** (2 / n), s)))
    m = Image.new("L", (big, big), 0); ImageDraw.Draw(m).polygon(pts, fill=255)
    return m.resize((size, size), Image.LANCZOS)

def legacy_icon(cell, size):
    art = Image.open(f"{ART}/icons/{cell}.png").convert("RGB")
    k = art.width * 0.04                       # trim the art's own corners/background
    art = art.crop((k, k, art.width - k, art.height - k))
    inner = round(size * 0.92)                 # Lineage 14.1 icons fill ~92 % of the canvas
    a = art.resize((inner, inner), Image.LANCZOS).convert("RGBA")
    out = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    off = (size - inner) // 2
    out.paste(a, (off, off), squircle(inner))
    return out

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True); open(path, "w").write(text)

shutil.rmtree(OUT, ignore_errors=True)
names = []
# framework: default wallpaper (1080x1920 phone)
name = "PioneerFramework"; names.append(name)
write(f"{OUT}/{name}/AndroidManifest.xml", MANIFEST.format(suffix="framework", target="android"))
wp = Image.open(f"{ART}/wallpaper-2520x3640.png").convert("RGB")
cw = round(wp.height * 1080 / 1920); x0 = 170
wall = wp.crop((x0, 0, x0 + cw, wp.height)).resize((1080, 1920), Image.LANCZOS)
# "-v4": framework-res and the apps were built with aapt1, which tags these
# configs v4; on Android 7 a config without it loses to the target's own
for cfg in ("drawable-nodpi-v4", "drawable-xxhdpi-v4"):
    os.makedirs(f"{OUT}/{name}/res/{cfg}", exist_ok=True)
    wall.save(f"{OUT}/{name}/res/{cfg}/default_wallpaper.jpg", quality=92, optimize=True)

for cell, suffix, target, res in APPS:
    name = f"PioneerIcon{suffix}"; names.append(name)
    write(f"{OUT}/{name}/AndroidManifest.xml", MANIFEST.format(suffix=suffix.lower(), target=target))
    for dens, px in DENS.items():
        icon = legacy_icon(cell, px)
        for rtype, rname in res:
            d = f"{OUT}/{name}/res/{rtype}-{dens}-v4"; os.makedirs(d, exist_ok=True)
            icon.save(f"{d}/{rname}.png", optimize=True)
write(f"{OUT}/LIST", "\n".join(names) + "\n")
print(f"{len(names)} overlays -> {OUT}")
